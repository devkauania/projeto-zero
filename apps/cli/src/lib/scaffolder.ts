import path from "node:path";
import fs from "node:fs/promises";
import type { WizardConfig } from "./config.js";
import { getRequiredConnectors } from "./config.js";
import {
  ensureDir,
  copyFile,
  writeJsonFile,
  findSeedConfigPath,
} from "./fs-utils.js";

const AGENT_TEMPLATES: Record<string, string> = {
  coder: `# ClaudeCoder Agent Prompt
**Role:** Backend logic developer
**Scope:** Node.js modules, Commander commands, filesystem operations
`,
  designer: `# AntigravityDesigner Agent Prompt
**Role:** Terminal UI/UX designer
**Scope:** picocolors themes, figlet banners, @clack/prompts flows
`,
  auditor: `# AntigravityAuditor Agent Prompt
**Role:** Quality assurance and test runner
**Scope:** Integration tests, CLI output validation
`,
  mcp: `# MCPConfigurator Agent Prompt
**Role:** MCP tool connector
**Scope:** Connect repository tools to the CLI agent pipeline

## Available Connectors
- **Supabase** — Database, auth, migrations, edge functions
- **Vercel** — Deployments, build logs, preview URLs
- **Stripe** — Products, prices, payment links
- **Figma** — Design context, screenshots, design system search
- **Netlify** — Deploy services, project management

## Configuration
See \`.agents/default-wizard-config.json\` for the full connector registry and defaults.
`,
};

export async function scaffoldProject(
  config: WizardConfig,
  targetDir: string
): Promise<string[]> {
  const root = path.resolve(targetDir);
  const created: string[] = [];

  // --- Core directories ---
  const dirs = [
    ".agents/prompts",
    "src",
    "src/commands",
    "src/lib",
  ];

  for (const dir of dirs) {
    const full = path.join(root, dir);
    const wasCreated = await ensureDir(full);
    if (wasCreated) created.push(dir + "/");
  }

  // --- Agent prompt templates ---
  if (config.includeTemplates) {
    for (const agent of config.agents) {
      const template = AGENT_TEMPLATES[agent];
      if (template) {
        const filePath = path.join(root, ".agents/prompts", `${agent}.md`);
        await fs.writeFile(filePath, template, "utf-8");
        created.push(`.agents/prompts/${agent}.md`);
      }
    }
  }

  // --- Copy seed config into the generated project ---
  const seedConfigPath = findSeedConfigPath(import.meta.url);
  if (seedConfigPath) {
    const destSeedConfig = path.join(root, ".agents", "default-wizard-config.json");
    await copyFile(seedConfigPath, destSeedConfig);
    created.push(".agents/default-wizard-config.json");
  }

  // --- .claude/ structure for MCP-enabled projects ---
  if (config.agents.includes("mcp")) {
    const claudeDir = path.join(root, ".claude");
    await ensureDir(claudeDir);
    created.push(".claude/");

    // Generate a settings stub listing required connectors
    const requiredConnectors = getRequiredConnectors(config);
    const settingsStub = {
      mcpConnectors: requiredConnectors,
      generatedAt: new Date().toISOString(),
      note: "Auto-generated by antigravity CLI. Edit as needed.",
    };
    const settingsPath = path.join(claudeDir, "settings.project.json");
    await writeJsonFile(settingsPath, settingsStub);
    created.push(".claude/settings.project.json");
  }

  // --- Project config marker ---
  const markerPath = path.join(root, ".agents", "project-config.json");
  await writeJsonFile(markerPath, {
    projectName: config.projectName,
    agents: config.agents,
    createdAt: new Date().toISOString(),
  });
  created.push(".agents/project-config.json");

  return created;
}
